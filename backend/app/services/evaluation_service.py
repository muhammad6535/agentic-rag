"""RAG evaluation service using LLM-as-judge.

Measures faithfulness (hallucination), answer relevance, context relevance,
and overall quality. Each metric is 0–1 where 1 is best.
"""

import json
import re
from typing import Optional
from langchain_ollama import ChatOllama
from langchain.prompts import ChatPromptTemplate
from langchain.schema import StrOutputParser
from app.config import settings


EVAL_SYSTEM_PROMPT = """You are an expert evaluator of RAG (Retrieval-Augmented Generation) systems. Your job is to assess the quality of answers generated by an AI system.

Evaluate the following:

1. FAITHFULNESS: Does each claim in the answer cite information from the provided context? Identify specific claims and whether they are supported.

2. ANSWER RELEVANCE: Does the answer directly address the user's question?

3. HALLUCINATION: Does the answer contain any information that is NOT present in the provided context?

For each claim, indicate SUPPORTED or UNSUPPORTED.

Return your analysis as a JSON object with this exact structure:
{{
    "claims": [
        {{"claim": "exact claim from answer", "supported": true/false, "evidence": "quoted text from context that supports it, or null if unsupported"}}
    ],
    "answer_relevance_score": 0.0-1.0,
    "answer_relevance_reasoning": "brief explanation",
    "overall_assessment": "brief summary of quality"
}}

Be strict — if a claim contains ANY detail not found in the context, mark it as unsupported.
"""

FAITHFULNESS_PROMPT = ChatPromptTemplate.from_messages([
    ("system", EVAL_SYSTEM_PROMPT),
    ("human", """CONTEXT:
{context}

QUESTION: {question}

ANSWER: {answer}

Evaluate this answer for faithfulness, relevance, and hallucination.""")
])


class EvaluationService:
    """Evaluates RAG output quality using LLM-as-judge."""

    def __init__(self):
        self.llm = ChatOllama(
            model=settings.llm_model,
            base_url=settings.ollama_base_url,
            temperature=0,
        )
        self.chain = FAITHFULNESS_PROMPT | self.llm | StrOutputParser()

    async def evaluate_full(
        self,
        question: str,
        answer: str,
        chunks: list[dict],
    ) -> dict:
        """
        Run full evaluation: faithfulness, hallucination, answer relevance, context relevance.

        Returns a dict with all metrics.
        """
        # 1. Context relevance via embedding scores (already computed during retrieval)
        context_scores = [c.get("score", 0) for c in chunks if c.get("score") is not None]
        context_relevance = sum(context_scores) / len(context_scores) if context_scores else 0.0

        # 2. LLM-as-judge for faithfulness, hallucination, answer relevance
        if not answer.strip() or not chunks:
            return self._empty_result(question, answer, chunks, context_relevance)

        context_text = self._format_context_for_eval(chunks)

        try:
            raw = await self.chain.ainvoke({
                "context": context_text,
                "question": question,
                "answer": answer,
            })
            parsed = self._parse_eval_output(raw, answer)

            supported = [c for c in parsed["claims"] if c["supported"]]
            unsupported = [c for c in parsed["claims"] if not c["supported"]]

            faithfulness = len(supported) / max(len(parsed["claims"]), 1)
            hallucination = len(unsupported) / max(len(parsed["claims"]), 1)

            return {
                "faithfulness_score": round(faithfulness, 4),
                "answer_relevance_score": round(parsed["answer_relevance_score"], 4),
                "context_relevance_score": round(context_relevance, 4),
                "hallucination_score": round(hallucination, 4),
                "overall_score": round(
                    (faithfulness + parsed["answer_relevance_score"] + context_relevance + (1 - hallucination)) / 4, 4
                ),
                "supported_claims": supported,
                "unsupported_claims": unsupported,
                "raw_eval": parsed,
            }
        except Exception as e:
            # Fallback: use heuristic metrics if LLM judge fails
            return self._heuristic_fallback(question, answer, chunks, context_relevance, str(e))

    def _format_context_for_eval(self, chunks: list[dict]) -> str:
        parts = []
        for i, c in enumerate(chunks):
            doc = c.get("document_name", "Unknown")
            idx = c.get("chunk_index", 0)
            parts.append(f"[Source: {doc}, Chunk {idx}]\n{c['content']}")
        return "\n\n---\n\n".join(parts)

    def _parse_eval_output(self, raw: str, answer: str) -> dict:
        """Parse JSON from LLM output, with fallback to regex extraction."""
        # Try direct JSON parse
        json_match = re.search(r"\{.*\}", raw, re.DOTALL)
        if json_match:
            try:
                data = json.loads(json_match.group())
                if "claims" in data and "answer_relevance_score" in data:
                    return data
            except json.JSONDecodeError:
                pass

        # Fallback: split answer into sentences and basic heuristic
        sentences = [s.strip() for s in re.split(r'[.!?]+', answer) if s.strip()]
        claims = []
        for s in sentences:
            claims.append({"claim": s, "supported": True, "evidence": None})

        return {
            "claims": claims,
            "answer_relevance_score": 0.5,
            "answer_relevance_reasoning": "Fallback: LLM output could not be parsed.",
            "overall_assessment": "Fallback evaluation used.",
        }

    def _empty_result(self, question: str, answer: str, chunks: list, ctx_rel: float) -> dict:
        return {
            "faithfulness_score": 0.0,
            "answer_relevance_score": 0.0,
            "context_relevance_score": ctx_rel,
            "hallucination_score": 0.0,
            "overall_score": ctx_rel / 4,
            "supported_claims": [],
            "unsupported_claims": [],
            "raw_eval": None,
        }

    def _heuristic_fallback(
        self, question: str, answer: str, chunks: list, ctx_rel: float, error: str
    ) -> dict:
        """Fallback using simple heuristics when LLM judge fails."""
        # Groundedness: check if source names are referenced
        source_refs = sum(
            1 for c in chunks
            if c.get("document_name", "").lower() in answer.lower()
        )
        faithfulness = min(source_refs / max(len(chunks), 1), 1.0)

        # Answer relevance: keyword overlap
        q_words = set(question.lower().split())
        a_words = set(answer.lower().split())
        overlap = len(q_words & a_words) / max(len(q_words), 1)
        relevance = min(overlap * 1.5, 1.0)

        # Hallucination: simplistic - if faithfulness is high, hallucination is low
        hallucination = 1.0 - faithfulness

        return {
            "faithfulness_score": round(faithfulness, 4),
            "answer_relevance_score": round(relevance, 4),
            "context_relevance_score": round(ctx_rel, 4),
            "hallucination_score": round(hallucination, 4),
            "overall_score": round(
                (faithfulness + relevance + ctx_rel + (1 - hallucination)) / 4, 4
            ),
            "supported_claims": [{"claim": s, "supported": True, "evidence": None}
                                 for s in re.split(r'[.!?]+', answer) if s.strip()],
            "unsupported_claims": [],
            "raw_eval": {"error": error, "fallback": True},
        }
